import { TOYBOX_THEMES } from './themes'
import { themeCssBlock } from './tokens'

const HEADER = '/* Generated by scripts/gen-themes.mjs from themes.ts. Do not edit by hand. */\n'

/** Full contents of themes.css: the first theme doubles as the unscoped default. */
export function themesCss(): string {
  return (
    HEADER +
    TOYBOX_THEMES.map((theme, i) => themeCssBlock(theme, i === 0 ? ':root,\n' : '')).join('\n')
  )
}
